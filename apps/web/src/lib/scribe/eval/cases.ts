export const EVAL_FIELDS = [
  "chiefComplaint",
  "history",
  "examination",
  "diagnosis",
  "medicines",
  "advice",
  "followUp",
] as const;

export type EvalField = (typeof EVAL_FIELDS)[number];

export const EVAL_PATTERNS = [
  "teaching",
  "negation",
  "conditional",
  "patient_guess",
  "small_talk",
  "mispronunciation",
  "no_medicine",
  "straight",
] as const;

export type EvalPattern = (typeof EVAL_PATTERNS)[number];
export type EvalLanguage = "en" | "ta" | "hi" | "mixed";

export type EvalCase = {
  id: string;
  language: EvalLanguage;
  pattern: EvalPattern;
  transcript: string;
  must: Partial<Record<EvalField, string[]>>;
  mustNot: Partial<Record<EvalField, string[]>>;
};

function note(
  id: string,
  language: EvalLanguage,
  pattern: EvalPattern,
  transcript: string,
  must: EvalCase["must"] = {},
  mustNot: EvalCase["mustNot"] = {},
): EvalCase {
  return { id, language, pattern, transcript, must, mustNot };
}

